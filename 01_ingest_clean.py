import requests

def get_temperature(latitude, longitude):
    url = "https://api.open-meteo.com/v1/forecast"

    params = {
        "latitude": latitude,
        "longitude": longitude,
        "hourly": "temperature_2m",
        "forecast_days": 1
    }

    for attempt in range(2):
        try:
            response = requests.get(
                url,
                params=params,
                timeout=10
            )

            if response.status_code != 200:
                reason = (
                    f"HTTP status {response.status_code}"
                )
                continue

            data = response.json()

            hourly = data.get("hourly")

            if (
                hourly is None or
                "temperature_2m" not in hourly or
                len(hourly["temperature_2m"]) == 0
            ):
                reason = "Hourly temperature missing"
                continue

            return hourly["temperature_2m"][0]

        except requests.exceptions.RequestException as e:
            reason = str(e)

    return None

