def sql_value(value):
    if pd.isna(value):
        return "NULL"

    if isinstance(value, (int, np.integer)):
        return str(int(value))

    if isinstance(value, (float, np.floating)):
        return str(value)

    # Text values are enclosed in single quotes
    return "'" + str(value).replace("'", "''") + "'"

